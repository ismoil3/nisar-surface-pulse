/** Language from the link, then the saved choice, then the browser; English otherwise. */
export function initialLang() {
  // "#lang=tg" (landing) or "#/map/water?…&lang=tg" (map route): read the part after "?" when there is one
  const h = location.hash.slice(1);
  const fromHash = new URLSearchParams(h.includes("?") ? h.split("?")[1] : h).get("lang");
  if (DICT[fromHash]) return fromHash;
  const fromSearch = new URLSearchParams(location.search).get("lang");
  if (DICT[fromSearch]) return fromSearch;
  try {
    const saved = localStorage.getItem("nsp_lang");
    if (DICT[saved]) return saved;
  } catch { /* storage unavailable */ }
  const nav = (navigator.language || "").toLowerCase();
  if (nav.startsWith("tg")) return "tg";
  if (nav.startsWith("ru")) return "ru";
  return "en";
}
export const saveLang = (l) => { try { localStorage.setItem("nsp_lang", l); } catch { /* ignore */ } };

export function t(key, vars = {}) {
  const v = DICT[current][key] ?? DICT.en[key];
  if (v == null) return key;
  if (typeof v === "function") return v(vars);
  return v.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}

/** Turns **bold** markers into <b> elements. */
export function rich(str) {
  return String(str).split(/(\*\*[^*]+\*\*)/g).map((part, i) =>
    part.startsWith("**") && part.endsWith("**") ? <b key={i}>{part.slice(2, -2)}</b> : <Fragment key={i}>{part}</Fragment>
  );
}
/** Shorthand: translated and rendered with bold markers. */
export const tr = (key, vars) => rich(t(key, vars));

