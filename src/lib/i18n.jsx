/** "2 Jul 2026" / "2 июля 2026" / "2 июли 2026"; short form without the year. */
export function fmtDateL(iso, short) {
  const [y, mo, d] = iso.split("-").map(Number);
  const M = MONTHS[current];
  if (short) return `${d} ${M.short[mo - 1]}`;
  return `${d} ${(M.full || M.short)[mo - 1]} ${y}`;
}

