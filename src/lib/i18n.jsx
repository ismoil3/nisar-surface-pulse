/** Latin (Tajik romanisation) to Cyrillic, for village names that OpenStreetMap only has in Latin. */
function toCyrillic(word, lang) {
  const tg = lang === "tg";
  const pairs = [
    ["kh", "х"], ["sh", "ш"], ["ch", "ч"], ["zh", "ж"], ["gh", tg ? "ғ" : "г"], ["ya", "я"], ["yu", "ю"], ["yo", "ё"],
    ["a", "а"], ["b", "б"], ["d", "д"], ["e", "е"], ["f", "ф"], ["g", "г"], ["h", tg ? "ҳ" : "х"], ["i", "и"],
    ["j", tg ? "ҷ" : "дж"], ["k", "к"], ["l", "л"], ["m", "м"], ["n", "н"], ["o", "о"], ["p", "п"], ["q", tg ? "қ" : "к"],
    ["r", "р"], ["s", "с"], ["t", "т"], ["u", "у"], ["v", "в"], ["w", "в"], ["x", "х"], ["y", "й"], ["z", "з"],
  ];
  let out = "", i = 0;
  const low = word.toLowerCase();
  while (i < word.length) {
    const hit = pairs.find(([l]) => low.startsWith(l, i));
    if (!hit) { out += word[i]; i++; continue; }
    const cap = word[i] !== low[i];
    out += cap ? hit[1][0].toUpperCase() + hit[1].slice(1) : hit[1];
    i += hit[0].length;
  }
  return out;
}

/** Name of an OpenStreetMap place in the current language. */
export function placeName(p) {
  if (!p) return "";
  // a local name in another script (e.g. Chinese for villages in Tibet) falls back to the English name
  const readable = (x) => x && /^[\p{Script=Latin}\p{Script=Cyrillic}\d\s.,'()–-]+$/u.test(x);
  if (current === "en") return p.name || (readable(p.local) ? p.local : "");
  const n = p.names?.[current] || (readable(p.local) ? p.local : p.name) || "";
  return /[А-Яа-яЁёҒғҚқҲҳҶҷӢӣӮӯ]/.test(n) ? n : toCyrillic(n, current);
}

